package outbound

import "testing"

func TestPublicAddressRejectsNonpublicDestinations(t *testing.T) {
	for _, host := range []string{
		"invalid", "0.0.0.0", "0.1.2.3", "10.0.0.1", "127.0.0.1",
		"100.64.0.0", "100.100.100.200", "100.127.255.255",
		"169.254.169.254", "172.16.0.1", "192.168.0.1",
		"192.0.0.1", "192.0.0.8", "192.0.0.11", "192.0.0.170", "192.0.0.255",
		"192.0.2.1", "192.88.99.2", "198.18.0.0", "198.19.255.255",
		"198.51.100.1", "203.0.113.1", "224.0.0.1", "240.0.0.1", "255.255.255.255",
		"::", "::1", "fc00::1", "fe80::1", "ff02::1",
		"::ffff:100.100.100.200", "::ffff:192.0.2.1", "::ffff:a00:1",
		"64:ff9b::a00:1", "64:ff9b::a9fe:a9fe", "64:ff9b::6464:64c8",
		"64:ff9b::7f00:1", "64:ff9b::192.168.0.1", "64:ff9b::192.0.2.1",
		"64:ff9b::1", "64:ff9b::f000:1", "64:ff9b::a00:1%lo0",
		"64:ff9b:1::1", "100::1", "100:0:0:1::1",
		"2001:1::4", "2001:2::1", "2001:1ff:ffff::1", "2001:db8::1", "2001:db8::1%lo0",
		"3fff::1", "3fff:fff:ffff::1", "5f00::1",
	} {
		t.Run(host, func(t *testing.T) {
			if publicAddress(host) {
				t.Fatal("nonpublic destination accepted")
			}
		})
	}
}

func TestPublicAddressPreservesPublicDestinations(t *testing.T) {
	for _, host := range []string{
		"1.1.1.1", "100.63.255.255", "100.128.0.0", "192.0.0.9", "192.0.0.10",
		"192.0.1.1", "192.0.3.1", "192.31.196.1", "192.52.193.1", "192.175.48.1",
		"198.17.255.255", "198.20.0.0", "203.0.112.1", "203.0.114.1",
		"::ffff:1.1.1.1", "::ffff:100.128.0.0", "::ffff:192.0.0.9",
		"64:ff9b::808:808", "64:ff9b::192.0.0.9", "64:ff9b::100.128.0.0",
		"2001::1", "2001:1::1", "2001:1::2", "2001:1::3",
		"2001:3::1", "2001:4:112::1", "2001:20::1", "2001:30::1", "2001:200::1",
		"2001:4860:4860::8888", "2002:808:808::1", "2620:4f:8000::1", "3fff:1000::1",
	} {
		t.Run(host, func(t *testing.T) {
			if !publicAddress(host) {
				t.Fatal("public destination rejected")
			}
		})
	}
}
